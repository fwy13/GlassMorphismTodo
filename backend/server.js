import express from 'express';
import helmet from 'helmet';
import { rateLimit } from 'express-rate-limit';
import pg from 'pg';

const { Pool } = pg;
const app = express();
app.disable('x-powered-by');
app.use(helmet());
app.use(express.json({ limit: '16kb' }));
app.use('/api', rateLimit({ windowMs: 60000, limit: 120, standardHeaders: 'draft-7', legacyHeaders: false }));

const pool = new Pool({
  host: process.env.POSTGRES_HOST || 'db',
  port: Number(process.env.POSTGRES_PORT || 5432),
  database: process.env.POSTGRES_DB || 'glassmorphismtodo',
  user: process.env.POSTGRES_USER || 'glassmorphismtodo',
  password: process.env.POSTGRES_PASSWORD,
  max: 10,
  connectionTimeoutMillis: 5000,
  idleTimeoutMillis: 30000,
});
pool.on('error', err => console.error('PostgreSQL idle client error:', err));

const select = 'SELECT id, title, completed, created_at FROM tasks';
const validId = id => /^[1-9][0-9]*$/.test(id) && Number.isSafeInteger(Number(id));
const config = {
  name: process.env.APP_NAME || 'Glass Todo',
  theme: process.env.APP_THEME || 'aurora',
  accent: process.env.APP_ACCENT || '#9084ff',
  accent2: process.env.APP_ACCENT2 || '#42d5ef',
};
// Express 4 does not automatically catch rejected promises from async route handlers.
const asyncHandler = fn => (req, res, next) => Promise.resolve(fn(req, res, next)).catch(next);

app.get('/api/health', asyncHandler(async (_req, res) => {
  await pool.query('SELECT 1');
  res.json({ ok: true });
}));
app.get('/api/config', (_req, res) => res.json(config));
app.get('/api/tasks', asyncHandler(async (_req, res) => {
  const { rows } = await pool.query(`${select} ORDER BY id DESC`);
  res.json({ tasks: rows });
}));
app.post('/api/tasks', asyncHandler(async (req, res) => {
  const title = req.body?.title;
  if (typeof title !== 'string' || !title.trim() || title.trim().length > 200) {
    return res.status(400).json({ error: 'Task title must be 1–200 characters.' });
  }
  const { rows } = await pool.query(
    'INSERT INTO tasks (title) VALUES ($1) RETURNING id, title, completed, created_at',
    [title.trim()],
  );
  res.status(201).json({ task: rows[0] });
}));
app.patch('/api/tasks/:id', asyncHandler(async (req, res) => {
  if (!validId(req.params.id) || typeof req.body?.completed !== 'boolean') {
    return res.status(400).json({ error: 'Invalid ID or completed value.' });
  }
  const { rows } = await pool.query(
    'UPDATE tasks SET completed = $1 WHERE id = $2 RETURNING id, title, completed, created_at',
    [req.body.completed, Number(req.params.id)],
  );
  if (!rows.length) return res.status(404).json({ error: 'Task not found.' });
  res.json({ task: rows[0] });
}));
app.delete('/api/tasks/:id', asyncHandler(async (req, res) => {
  if (!validId(req.params.id)) return res.status(400).json({ error: 'Invalid ID.' });
  const result = await pool.query('DELETE FROM tasks WHERE id = $1', [Number(req.params.id)]);
  if (!result.rowCount) return res.status(404).json({ error: 'Task not found.' });
  res.json({ deleted: true });
}));
app.use('/api', (_req, res) => res.status(404).json({ error: 'Not found.' }));
app.use((err, _req, res, _next) => {
  console.error(err);
  res.status(err.status >= 400 && err.status < 500 ? err.status : 500).json({ error: 'Request failed.' });
});

async function main() {
  // PostgreSQL initialization runs only after the db container is healthy.
  await pool.query(`CREATE TABLE IF NOT EXISTS tasks (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL,
    completed BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
  )`);
  const server = app.listen(3000, '0.0.0.0', () => console.log(`${config.name}: API ready`));
  let stopping = false;
  const shutdown = () => {
    if (stopping) return;
    stopping = true;
    server.close(async () => {
      try { await pool.end(); } finally { process.exit(0); }
    });
  };
  process.on('SIGTERM', shutdown);
  process.on('SIGINT', shutdown);
}
main().catch(async err => {
  console.error('Cannot initialize PostgreSQL:', err);
  await pool.end().catch(() => {});
  process.exit(1);
});
